"""
Step 1, big version: tens of GB of Python from GitHub, far too much to hold in memory.

prepare.py builds one big string and encodes it in one go. That stops working at this
size, so this script streams instead: each worker process reads one compressed shard of
the dataset a file at a time, cleans it, encodes it, and writes the tokens straight to
disk. 32 cores encode 32 shards at once.

  bash download.sh                                   # the raw data, into data/raw/ (~13 GB)
  uv run prepare_big.py --vocab_size 16384           # -> data/code-bpe16384/
  uv run prepare_big.py --tokenizer data/code-bpe16384/meta.json   # another machine: same tokens

The data is codeparrot/codeparrot-clean from Hugging Face: ~5M Python files from public
GitHub repositories, with exact duplicates and auto-generated files already removed.
python+docs+packages is added too if it has been prepared.
"""

import argparse
import gzip
import json
import random
import re
import shutil
import string
import time
from array import array
from multiprocessing import Pool
from pathlib import Path

import numpy as np

from tokenizer import EOT, Tokenizer

DATA_DIR = Path(__file__).parent / "data"
RAW_DIR = DATA_DIR / "raw" / "codeparrot"
EXTRA = DATA_DIR / "python+docs+packages" / "input.txt"
ALLOWED = set(string.printable) - set("\t\r\x0b\x0c") | {"\n"}  # the same characters as before
VAL_TOKENS = 10_000_000


def clean(code):
    """Returns the file ready to train on, or None to skip it."""
    code = code.replace("\r\n", "\n").expandtabs(8)  # tabs indent to 8, as Python reads them
    if not set(code) <= ALLOWED:
        return None  # non-ASCII (about a fifth of files): keeps the vocabulary small
    if max(map(len, code.splitlines()), default=0) > 1000:
        return None  # data tables and minified code
    return code


def documents(shard):
    """Every usable file in one shard, each ending with the end-of-text token."""
    with gzip.open(shard, "rt", encoding="utf-8") as f:
        for line in f:
            rec = json.loads(line)
            if rec["autogenerated"]:
                continue
            code = clean(rec["content"])
            if code is not None and set(rec["path"]) <= ALLOWED:  # paths can have accents too
                yield f"# file: {rec['path']}\n{code}\n{EOT}"


def extra_documents():
    """python+docs+packages, without the part held out as python+docs' val text, so older
    models and this one can still be compared on that text."""
    if not EXTRA.exists():
        return []
    text = EXTRA.read_text(encoding="utf-8")
    base_len = len((DATA_DIR / "python+docs" / "input.txt").read_text(encoding="utf-8"))
    text = text[:len(text) - (base_len - int(0.9 * base_len))]
    docs = re.split(r"(?=^# (?:file|docs): )", text, flags=re.M)
    return [d + EOT for d in docs if d and set(d) <= ALLOWED]


def encode_shard(job):
    """Runs in a worker process: encode one shard to its own .bin file."""
    shard, out, meta = job
    tok = Tokenizer(meta["chars"], meta["merges"])
    docs = extra_documents() if shard == "extra" else documents(shard)
    ids, chars, n = array("H"), 0, 0  # array("H"): 2 bytes per token, not ~30 for a Python int
    for doc in docs:
        ids.extend(tok.encode(doc))
        chars += len(doc)
        n += 1
    with open(out, "wb") as f:
        ids.tofile(f)
    return len(ids), chars, n


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--vocab_size", type=int, default=16384)
    p.add_argument("--tokenizer", type=Path, help="reuse this meta.json's tokenizer instead of training one")
    p.add_argument("--sample_mb", type=int, default=200, help="how much text to train the tokenizer on")
    p.add_argument("--shards", type=int, default=0, help="use only the first N shards (0 = all)")
    p.add_argument("--workers", type=int, default=32)
    args = p.parse_args()

    shards = sorted(RAW_DIR.glob("*.json.gz"))
    if args.shards:
        shards = shards[:args.shards]
    if not shards:
        raise SystemExit(f"No shards in {RAW_DIR}. Run: bash download.sh")

    if args.tokenizer:
        meta = json.loads(args.tokenizer.read_text())
        out_dir = args.tokenizer.parent
    else:
        # The tokenizer learns from a sample: the most common pairs in 200 MB of code
        # are the same as in 50 GB.
        t0 = time.time()
        sample, size = [], 0
        for doc in documents(shards[0]):
            sample.append(doc)
            size += len(doc)
            if size > args.sample_mb * 1_000_000:
                break
        print(f"Training a {args.vocab_size}-token BPE tokenizer on {size / 1e6:.0f} MB of code...")
        tok = Tokenizer.train("".join(sample), args.vocab_size, chars=ALLOWED | {EOT})
        meta = {"chars": tok.chars, "merges": tok.merges}
        print(f"  done in {time.time() - t0:.0f}s. Last merges: {[tok.vocab[i] for i in range(tok.vocab_size - 8, tok.vocab_size)]}")
        out_dir = DATA_DIR / f"code-bpe{args.vocab_size}"
    out_dir.mkdir(parents=True, exist_ok=True)
    assert len(meta["chars"]) + len(meta["merges"]) <= 65536, "token ids must fit in uint16"

    # The extra data goes in as one more "shard"; then shuffle so files from the same
    # shard don't all sit together. (Fixed seed, so every machine gets the same order.)
    jobs = [str(s) for s in shards] + ["extra"]
    random.Random(0).shuffle(jobs)
    parts = out_dir / "parts"
    parts.mkdir(exist_ok=True)
    jobs = [(j, parts / f"{i:03d}.bin", meta) for i, j in enumerate(jobs)]
    print(f"Encoding {len(jobs)} shards with {args.workers} processes...")
    t0 = time.time()
    tokens = chars = docs = 0
    with Pool(args.workers) as pool:
        for i, (n_tok, n_chars, n_docs) in enumerate(pool.imap(encode_shard, jobs)):
            tokens, chars, docs = tokens + n_tok, chars + n_chars, docs + n_docs
            print(f"  {i + 1}/{len(jobs)} shards | {docs:,} files | {chars / 1e9:.1f}G characters"
                  f" -> {tokens / 1e9:.2f}G tokens | {time.time() - t0:.0f}s", flush=True)

    # The first VAL_TOKENS of the first part are held out; everything else is train.
    first = np.fromfile(jobs[0][1], dtype=np.uint16)
    first[:VAL_TOKENS].tofile(out_dir / "val.bin")
    with open(out_dir / "train.bin", "wb") as out:
        first[VAL_TOKENS:].tofile(out)
        for _, part, _ in jobs[1:]:
            with open(part, "rb") as f:
                shutil.copyfileobj(f, out, 1 << 24)
    shutil.rmtree(parts)

    tok = Tokenizer(meta["chars"], meta["merges"])
    meta["chars_per_token"] = len(tok.decode(first[:VAL_TOKENS].tolist())) / VAL_TOKENS
    (out_dir / "meta.json").write_text(json.dumps(meta))
    print(f"Wrote {tokens - VAL_TOKENS:,} train and {VAL_TOKENS:,} val tokens to {out_dir}"
          f" ({meta['chars_per_token']:.2f} characters per token)")


if __name__ == "__main__":
    main()
